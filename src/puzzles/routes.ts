import type { RequestHandler } from "express";
import { z } from "zod";
import { HttpError } from "../errors.js";
import { requireGame } from "../games/lookup.js";
import { parseSlug } from "../games/slug.js";
import { nextUtcDateString, openPuzzleDates, toUtcDateString } from "../scores/dates.js";
import {
    getPriceIsNicePuzzle,
    prefetchPriceIsNicePuzzle,
    PRICE_IS_NICE_SLUG,
    PuzzleUnavailableError,
    puzzleResponse,
} from "./price-is-nice.js";

// A repeated parameter arrives as an array and fails the string check, like the history query.
const puzzleQuerySchema = z.object({ puzzleDate: z.iso.date() });

// GET /games/:slug/puzzle?puzzleDate=YYYY-MM-DD
// The day's puzzle for games whose puzzle the server picks; today only Price Is Nice. Every other
// game generates its puzzle on the client from the date. No login: guests play too.
export const getDailyPuzzle: RequestHandler = async (req, res) => {
    const slug = parseSlug(req.params.slug);

    const parsed = puzzleQuerySchema.safeParse(req.query);
    if (!parsed.success) {
        throw new HttpError(400, "invalid_puzzle_date", "puzzleDate must be a date in YYYY-MM-DD format");
    }
    const { puzzleDate } = parsed.data;

    // Same window as score submission: no peeking at tomorrow's game.
    const now = new Date();
    if (!openPuzzleDates(now).has(puzzleDate)) {
        throw new HttpError(400, "puzzle_date_closed", "Only today's puzzle (UTC) can be requested");
    }

    const game = await requireGame(slug);
    if (game.slug !== PRICE_IS_NICE_SLUG) {
        throw new HttpError(404, "puzzle_not_served", `${game.name} puzzles are generated by the game, not the server`);
    }

    const row = await getPriceIsNicePuzzle(puzzleDate).catch((err: unknown) => {
        if (err instanceof PuzzleUnavailableError) {
            throw new HttpError(503, "puzzle_unavailable", "Today's puzzle isn't available right now; try again shortly");
        }
        throw err;
    });

    // Pick tomorrow's game ahead of time, so the first player after midnight doesn't wait for Steam.
    if (puzzleDate === toUtcDateString(now)) prefetchPriceIsNicePuzzle(nextUtcDateString(puzzleDate));

    // The same for everyone and fixed once picked, so a short shared cache is safe.
    res.set("Cache-Control", "public, max-age=300");
    res.json({ puzzle: puzzleResponse(row) });
};
